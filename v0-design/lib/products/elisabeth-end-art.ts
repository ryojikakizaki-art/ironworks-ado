// Élisabeth 唐草エンドの実物写真トレース（シミュレーター側面図用）。
// 実物写真 → 2値化 → potrace で自動トレースしたシルエットなので、
// 手描きベジェと違い形は写真に忠実。生成スクリプトは作業用 scratchpad の
// finalize_a.py（PIL + scipy + potrace）。
//
// 座標系: viewBox 0 0 viewW viewH（1unit = クロップ後の元写真 1px）。
// バーは片側の縁で切れており、その縁の y=attachY がレール接続点・barPx がバー太さ。
// レール（strokeWidth）に対し barPx が一致するよう縮尺して接続する。

export interface EndArt {
  viewW: number
  viewH: number
  /** バー切り口の中心 y（レール接続点） */
  attachY: number
  /** バー切り口の太さ (px)。レールの strokeWidth に合わせる基準 */
  barPx: number
  /** potrace が出力した <g> の transform（そのまま入れ子で使う） */
  innerTransform: string
  d: string
}

